// Netora PWA Service Worker v3 - Auto Invalidate Cache
const CACHE_NAME = 'netora-app-v3';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => caches.delete(key))
      );
    }).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const url = (event.request && event.request.url) ? event.request.url.toLowerCase() : '';
  // Never intercept admin scripts or API endpoints
  if (url.includes('admin') || url.includes('/api/')) {
    event.respondWith(fetch(event.request));
    return;
  }
  event.respondWith(
    fetch(event.request).catch(() => caches.match(event.request))
  );
});
